# Filter excluded names and SKIP placeholders
filtered = [e for e in ENTRIES if e[1] not in EXCLUDE_DOMESTIC and e[1] != "—"]

def esc(s):
    if s is None:
        return ""
    return str(s).replace("\\", "\\\\").replace("'", "\\'").replace("\n", " ")

def fmt_entry(e):
    (id_, name, nameEn, gender, role, country, city, region, appointed, cred,
     prev, highlights, rank, lat, lng, source, *rest) = e
    notes = rest[0] if rest else ""
    vt = rest[1] if len(rest) > 1 else "official"
    prev_js = "[" + ", ".join(f"'{esc(p)}'" for p in prev) + "]"
    return (
        f"  D('{esc(id_)}', '{esc(name)}', '{esc(nameEn)}', '{esc(gender)}', "
        f"'{esc(role)}', '{esc(country)}', '{esc(city)}', '{esc(region)}', "
        f"'{esc(appointed)}', '{esc(cred)}', {prev_js}, '{esc(highlights)}', "
        f"'{esc(rank)}', {lat}, {lng}, '{esc(source)}', '{esc(notes)}', '{esc(vt)}'),"
    )

counts = Counter(e[7] for e in filtered)
role_counts = Counter(e[4] for e in filtered)
scope = "；".join(f"{r} {counts[r]} 处" for r in ["亚太", "欧洲", "北美", "拉美", "非洲", "中东", "国际组织"] if counts[r])

body = HEADER.replace("{scope}", scope).replace("{as_of}", "2026-07-14")
body += "\nexport const DIPLOMATIC_CORPS_2026 = [\n"
body += "\n".join(fmt_entry(e) for e in filtered)
body += "\n];\n\n"
body += f"export const DIPLOMATIC_CORPS_COUNT = {{ total: {len(filtered)}, "
body += ", ".join(f"'{k}': {v}" for k, v in sorted(counts.items()))
body += " };\n"

OUT.write_text(body, encoding="utf-8")
print(f"Wrote {len(filtered)} entries to {OUT}")
