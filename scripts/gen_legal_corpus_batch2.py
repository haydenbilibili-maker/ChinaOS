def write_batch2() -> int:
    seed = {e["id"]: e for e in parse_legal_seed()}
    count = 0
    for eid, sections in CONTENT.items():
        entry = seed.get(eid)
        if not entry:
            print(f"WARN: {eid} not in seed")
            continue
        rel = (
            f"laws/{eid}.md" if eid.startswith("law-")
            else f"regulations/{eid}.md" if eid.startswith("reg-")
            else f"interpretations/{eid}.md"
        )
        path = ROOT / "app/public/legal-corpus" / rel
        if path.is_file():
            print(f"  skip existing {rel}")
            continue
        meta = f"{entry['revisedDate']} · {entry['issuer']} · {entry['status']}"
        # prepend overview from seed
        full_sections = [
            ("概述", [entry["summary"]]),
            *sections,
        ]
        if entry["keyArticles"]:
            full_sections.append(
                ("重点条款索引", [f"**{a}**" for a in entry["keyArticles"]])
            )
        content = law_doc(entry["title"], meta, full_sections)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"  wrote {rel} ({len(content)} chars)")
        count += 1
    return count


if __name__ == "__main__":
    n = write_batch2()
    print(f"Legal batch-2: {n} new files")
