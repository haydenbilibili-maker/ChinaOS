STATE_TYPES = ("中科院", "工程院", "部属", "行业")


def js_str(s: str) -> str:
    return s.replace("\\", "\\\\").replace("'", "\\'")


def emit_private_line(e: tuple) -> str:
    id_, name, parent, field, prov, founded, scale, tier, source, notes, tags = e
    return (
        f"  P('{id_}', '{js_str(name)}', '{js_str(parent)}', '{js_str(field)}', "
        f"'{prov}', {founded}, '{js_str(scale)}', '{js_str(tier)}', '{js_str(source)}', "
        f"'{js_str(notes)}', '{tags}'),"
    )


def validate() -> None:
    text = JS.read_text(encoding="utf-8")
    private_ids = set(re.findall(r"P\('(ri-[^']+)'", text))
    facility_ids = set(re.findall(r"F\('(lsf-[^']+)'", text))
    state_types = re.findall(r"R\('ri-[^']+', '[^']+', '([^']+)'", text)

    print(f"JS file: {JS.relative_to(ROOT)}")
    print(f"  State entries (R): {len(state_types)}")
    print(f"  Private entries (P): {len(private_ids)}")
    print(f"  Facility entries (F): {len(facility_ids)}")
    print(f"  Script PRIVATE_ENTRIES: {len(PRIVATE_ENTRIES)}")
    for t in STATE_TYPES:
        print(f"    {t}: {state_types.count(t)}")
    print(f"    民企科研: {len(private_ids)}")
    print(f"    大科学装置: {len(facility_ids)}")
    print(f"  Total: {len(state_types) + len(private_ids) + len(facility_ids)}")

    script_ids = {e[0] for e in PRIVATE_ENTRIES}
    missing = script_ids - private_ids
    extra = private_ids - script_ids
    if missing:
        print(f"  WARN: in script but not JS: {sorted(missing)}")
    if extra:
        print(f"  WARN: in JS but not script: {sorted(extra)}")
    if not missing and not extra and len(private_ids) == len(PRIVATE_ENTRIES):
        print("  OK: private entries in sync")
    if len(facility_ids) >= 30:
        print(f"  OK: {len(facility_ids)} large science facilities")
    else:
        print(f"  WARN: only {len(facility_ids)} facilities (target 30+)")


if __name__ == "__main__":
    validate()
