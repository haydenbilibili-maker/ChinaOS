def esc(s):
    return json.dumps(s, ensure_ascii=False)

def fmt_events(events):
    if not events:
        return "[]"
    parts = []
    for fr, to, desc in events:
        parts.append(f"{{ from: {esc(fr)}, to: {esc(to)}, desc: {esc(desc)} }}")
    return f"[{', '.join(parts)}]"

