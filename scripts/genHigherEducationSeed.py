def slugify(name):
    if name in META:
        return META[name][0]
    if name in SLUG_MAP:
        return SLUG_MAP[name]
    raise KeyError(f"Missing slug for: {name}")

def tags_for(name):
    n = norm(name)
    tags = []
    if n in C9:
        tags.append("C9")
    if n in LIST_985:
        tags.append("985")
    if n in LIST_211:
        tags.append("211")
    if n in LIST_DFC:
        tags.append("双一流")
    return tags

def primary_tier(tags):
    if "C9" in tags:
        return "C9"
    if "985" in tags:
        return "985"
    if "211" in tags:
        return "211"
    return "双一流"

def build_record(name):
    n = norm(name)
    tags = tags_for(n)
    if not tags:
        return None
    tier = primary_tier(tags)
    tag_str = ",".join(tags)
    if n in META:
        sid, typ, region, founding, strengths, rank_notes, notes = META[n]
    else:
        sid = slugify(n)
        typ = infer_type(n)
        region = infer_region(n)
        founding = None
        strengths = f"{typ}类学科"
        rank_notes = f"{'/'.join(tags)}·第二轮双一流建设高校" if "双一流" in tags else f"{'/'.join(tags)}·211工程"
        notes = f"{n}为{'/'.join(tags)}建设高校，机构信息截至公开名录。"
    rid = f"he-{sid}"
    founding_s = str(founding) if founding else ""
    notes_s = notes.replace("'", "\\'")
    rank_s = rank_notes.replace("'", "\\'")
    strengths_s = strengths.replace("'", "\\'")
    return (
        f"  U('{rid}', '{n}', '{tier}', '{tag_str}', '{typ}', '{region}', "
        f"'{strengths_s}', '{rank_s}', {founding_s or 'null'}, "
        f"'教育部/发改委公开名录', '{notes_s}'),"
    )

