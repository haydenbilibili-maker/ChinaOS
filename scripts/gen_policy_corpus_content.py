def policy_doc(title: str, meta: str, sections: list[tuple[str, list[str]]]) -> str:
    parts = [f"# {title}", "", f"> {meta}", ""]
    for sec, paras in sections:
        parts.append(f"## {sec}")
        parts.append("")
        for p in paras:
            parts.append(p)
            parts.append("")
    return "\n".join(parts).strip() + "\n"


