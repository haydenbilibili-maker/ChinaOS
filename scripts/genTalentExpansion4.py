def js_str(s: str) -> str:
    return str(s).replace("\\", "\\\\").replace("'", "\\'")


def normalize_name(n: str) -> str:
    return re.sub(r"\s+", "", (n or "").strip())


def collect_existing_names() -> set[str]:
    names: set[str] = set()
    skip_files = {"talentBulkExpansion2026_part4.js"}
    for path in DB.glob("*.js"):
        if path.name in skip_files:
            continue
        text = path.read_text(encoding="utf-8", errors="ignore")
        for m in re.finditer(r"name:\s*['\"]([^'\"]{2,12})['\"]", text):
            names.add(normalize_name(m.group(1)))
    return names


EXISTING = collect_existing_names()
SKIP_LOG: list[str] = []


def keep(name: str) -> bool:
    n = normalize_name(name)
    if not n or n in EXISTING:
        SKIP_LOG.append(name)
        return False
    EXISTING.add(n)
    return True


def fmt_events(events):
    parts = []
    for fr, to, desc in events:
        parts.append(f"{{ from: '{js_str(fr)}', to: '{js_str(to)}', desc: '{js_str(desc)}' }}")
    return f"[{', '.join(parts)}]"


def wp(obj: dict) -> str:
    parts = []
    for k, v in obj.items():
        if v is None or v == "":
            continue
        if isinstance(v, bool):
            parts.append(f"{k}: {'true' if v else 'false'}")
        elif isinstance(v, (int, float)):
            parts.append(f"{k}: {v}")
        elif isinstance(v, list) and v and isinstance(v[0], dict):
            parts.append(f"{k}: {v}")  # preformatted
        else:
            parts.append(f"{k}: '{js_str(str(v))}'")
    return "withProvenance({ " + ", ".join(parts) + " })"


