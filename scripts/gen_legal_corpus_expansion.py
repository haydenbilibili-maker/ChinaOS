def law_doc(title: str, meta: str, sections: list[tuple[str, list[str]]]) -> str:
    parts = [f"# {title}", "", f"> {meta}", ""]
    for sec_title, articles in sections:
        parts.append(f"## {sec_title}")
        parts.append("")
        for art in articles:
            if art.startswith("###"):
                parts.append(art)
            else:
                parts.append(f"### {art.split(' ')[0] if art[:3].isdigit() or art.startswith('第') else '条款'}")
                parts.append("")
                parts.append(art if not art.startswith("第") else art)
            parts.append("")
    return "\n".join(parts).strip() + "\n"


