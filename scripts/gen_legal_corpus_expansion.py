def write_all() -> int:
    LAWS.mkdir(parents=True, exist_ok=True)
    REGS.mkdir(parents=True, exist_ok=True)
    count = 0
    for rel, content in FILES.items():
        path = ROOT / "app" / "public" / "legal-corpus" / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"  wrote {rel} ({len(content)} chars)")
        count += 1
    return count


if __name__ == "__main__":
    n = write_all()
    print(f"Expansion batch: {n} files")
