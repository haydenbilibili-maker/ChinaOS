def js_str(s):
    return s.replace("\\", "\\\\").replace("'", "\\'")


def emit_rows(name, fn, rows):
    lines = [f"export const {name} = ["]
    for args in rows:
        if len(args) == 8:
            lines.append(
                f"  {fn}('{args[0]}', '{js_str(args[1])}', '{js_str(args[2])}', '{js_str(args[3])}', "
                f"'{js_str(args[4])}', '{js_str(args[5])}', '{args[6]}', '{js_str(args[7])}'),"
            )
        else:
            lines.append(
                f"  {fn}('{args[0]}', '{js_str(args[1])}', '{js_str(args[2])}', '{js_str(args[3])}', "
                f"'{js_str(args[4])}', '{js_str(args[5])}', '{args[6]}', '{js_str(args[7])}', '{js_str(args[8])}'),"
            )
    lines.append("];")
    return lines


