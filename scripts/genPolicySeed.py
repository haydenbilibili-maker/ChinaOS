def js_val(v, indent=0):
    sp = "  " * indent
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        if not v:
            return "[]"
        if all(isinstance(x, str) for x in v):
            return "[" + ", ".join(json.dumps(x, ensure_ascii=False) for x in v) + "]"
        items = ",\n".join(f"{sp}  {js_val(x, indent + 1)}" for x in v)
        return f"[\n{items}\n{sp}]"
    if isinstance(v, dict):
        if not v:
            return "{}"
        lines = []
        for k, val in v.items():
            lines.append(f"{sp}  {k}: {js_val(val, indent + 1)}")
        return "{\n" + ",\n".join(lines) + f",\n{sp}}}"
    return json.dumps(v, ensure_ascii=False)


def js_obj(d, indent=0):
    sp = "  " * indent
    lines = []
    for k, v in d.items():
        lines.append(f"{sp}  {k}: {js_val(v, indent + 1)}")
    return "{\n" + ",\n".join(lines) + f",\n{sp}}}"


