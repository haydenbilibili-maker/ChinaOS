def fix_depth_relate_buttons(text: str) -> tuple[str, int]:
    n = 0
    for tab, label in sorted(DEPTH_TAB_LABELS.items(), key=lambda x: len(x[0]), reverse=True):
        pat = (
            r'(<button onclick="switchTab\(\''
            + re.escape(tab)
            + r'\'\)[^>]*class="depth-relate-tag">)\?+(</button>)'
        )
        repl = r"\1" + label + r"\2"
        new_t, c = re.subn(pat, repl, text)
        if c:
            text = new_t
            n += c
    return text, n


def main() -> None:
    text = PATH.read_text(encoding="utf-8")
    pairs = sorted(REPLACEMENTS, key=lambda x: len(x[0]), reverse=True)
    n = 0
    for old, new in pairs:
        if old in text:
            c = text.count(old)
            text = text.replace(old, new)
            n += c
    text, n2 = fix_depth_relate_buttons(text)
    PATH.write_text(text, encoding="utf-8")
    print(f"china.html: static {n} replacement(s); depth-relate {n2} button(s); rules {len(pairs)}")


if __name__ == "__main__":
    main()
