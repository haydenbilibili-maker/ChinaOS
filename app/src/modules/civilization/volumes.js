export function sectionCount(vol) {
  return (vol?.sections?.length || 0) + (vol?.frameworks?.length || 0);
}

export function wordEstimate(vol) {
  const text = [
    vol?.thesis,
    ...(vol?.sections || []).flatMap((s) => [s.lead, ...(s.body || []), ...(s.cards || []).map((c) => c.body)]),
    ...(vol?.frameworks || []).flatMap((f) => [f.body, ...(f.pillars || []).flatMap((p) => p)]),
  ].filter(Boolean).join('');
  return text.length;
}

